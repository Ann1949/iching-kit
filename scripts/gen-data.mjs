// Generates src/data/classic.ts from the site's hexagram dataset.
//
//   node scripts/gen-data.mjs [path-to-site/lib/data]
//
// Source: site/src/lib/data/hexagrams.json (Zhouyi 卦辞 / 爻辞, public domain)
//         site/src/lib/data/hexagramNames.ts (pinyin only)
//
// What is NOT copied: English translations, interpretations, articles, or any
// other editorial content from the site. Those stay proprietary.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const kitRoot = path.resolve(here, "..");
const siteData = process.argv[2]
  ? path.resolve(process.argv[2])
  : path.resolve(kitRoot, "..", "site", "src", "lib", "data");

const source = JSON.parse(fs.readFileSync(path.join(siteData, "hexagrams.json"), "utf8"));
const namesSource = fs.readFileSync(path.join(siteData, "hexagramNames.ts"), "utf8");

// --- pinyin from the site's name table (pinyin is a romanisation, not a translation)
const pinyinById = new Map();
for (const m of namesSource.matchAll(/id:\s*(\d+),\s*pinyin:\s*"([^"]+)"/g)) {
  pinyinById.set(Number(m[1]), m[2]);
}

// --- short English keywords, written for this package. Deliberately generic
// descriptors rather than any published translation's titles.
const KEYWORDS = [
  "Creative", "Receptive", "Initial Difficulty", "Inexperience", "Waiting", "Conflict",
  "The Army", "Union", "Small Restraint", "Conduct", "Peace", "Stagnation",
  "Fellowship", "Great Possession", "Modesty", "Enthusiasm", "Following", "Repair",
  "Approach", "Contemplation", "Biting Through", "Adornment", "Disintegration", "Return",
  "Innocence", "Great Restraint", "Nourishment", "Great Excess", "The Abyss", "Fire",
  "Attraction", "Duration", "Retreat", "Great Power", "Advance", "Darkening",
  "The Family", "Opposition", "Obstruction", "Release", "Decrease", "Increase",
  "Breakthrough", "Encounter", "Gathering", "Ascending", "Adversity", "The Well",
  "Revolution", "The Cauldron", "Thunder", "Stillness", "Gradual Progress", "Marriage",
  "Abundance", "Wandering", "Gentleness", "Joy", "Dispersion", "Limitation",
  "Sincerity", "Small Excess", "Completion", "Incompletion",
];

const TRIGRAM_PINYIN = { 乾: "Qian", 兑: "Dui", 离: "Li", 震: "Zhen", 巽: "Xun", 坎: "Kan", 艮: "Gen", 坤: "Kun" };
const TRIGRAM_ENGLISH = { 天: "Heaven", 泽: "Lake", 火: "Fire", 雷: "Thunder", 风: "Wind", 水: "Water", 山: "Mountain", 地: "Earth" };

const trigramByXiantian = new Map(source.trigrams.map((t) => [t.xiantian, t]));

function linesOfHexagram(hex) {
  const lower = trigramByXiantian.get(hex.lower);
  const upper = trigramByXiantian.get(hex.upper);
  if (!lower || !upper) throw new Error(`hexagram ${hex.id}: unknown trigram pair`);
  return [...lower.lines, ...upper.lines];
}

const trigrams = source.trigrams.map((t) => ({
  xiantian: t.xiantian,
  pinyin: TRIGRAM_PINYIN[t.name],
  name: t.name,
  nature: t.nature,
  english: TRIGRAM_ENGLISH[t.nature],
  symbol: t.symbol,
  lines: t.lines,
}));

const hexagrams = source.hexagrams
  .map((hex) => {
    const lines = linesOfHexagram(hex);
    return {
      id: hex.id,
      pinyin: pinyinById.get(hex.id),
      name: hex.name,
      keyword: KEYWORDS[hex.id - 1],
      upper: hex.upper,
      lower: hex.lower,
      binary: lines.join(""),
      lines,
      guaCi: hex.guaCi,
      yaoCi: hex.yaoCi,
      ...(hex.yong ? { yong: hex.yong } : {}),
    };
  })
  .sort((a, b) => a.id - b.id);

if (hexagrams.length !== 64) throw new Error(`expected 64 hexagrams, got ${hexagrams.length}`);
for (const h of hexagrams) {
  if (!h.pinyin) throw new Error(`hexagram ${h.id}: missing pinyin`);
  if (h.lines.length !== 6) throw new Error(`hexagram ${h.id}: wrong line count`);
  if (h.yaoCi.length !== 6) throw new Error(`hexagram ${h.id}: wrong yao count`);
}

function q(value) {
  return JSON.stringify(value);
}

const out = [];
out.push(`// 64 hexagrams and 8 trigrams of the I Ching (Zhouyi).`);
out.push(`//`);
out.push(`// The Chinese 卦辞 / 爻辞 below are the classical text of the Zhouyi, which is in`);
out.push(`// the public domain. Structure — King Wen order, trigram pair, bottom-up line`);
out.push(`// order, binary form — is mathematical. No modern translation, commentary, or`);
out.push(`// editorial interpretation is included.`);
out.push(`//`);
out.push(`// Generated by scripts/gen-data.mjs. Do not edit by hand.`);
out.push(``);
out.push(`import type { Hexagram, Trigram } from "../types.js";`);
out.push(``);
out.push(`/** The eight trigrams, in 先天 (Fu Xi) order. \`lines\` are bottom-up. */`);
out.push(`export const TRIGRAMS: Trigram[] = [`);
for (const t of trigrams) {
  out.push(
    `  { xiantian: ${t.xiantian}, pinyin: ${q(t.pinyin)}, name: ${q(t.name)}, nature: ${q(t.nature)}, english: ${q(t.english)}, symbol: ${q(t.symbol)}, lines: [${t.lines.join(", ")}] },`,
  );
}
out.push(`];`);
out.push(``);
out.push(`/** The 64 hexagrams in King Wen order. \`lines\` and \`binary\` are bottom-up. */`);
out.push(`export const HEXAGRAMS: Hexagram[] = [`);
for (const h of hexagrams) {
  out.push(`  {`);
  out.push(`    id: ${h.id},`);
  out.push(`    pinyin: ${q(h.pinyin)},`);
  out.push(`    name: ${q(h.name)},`);
  out.push(`    keyword: ${q(h.keyword)},`);
  out.push(`    upper: ${h.upper},`);
  out.push(`    lower: ${h.lower},`);
  out.push(`    binary: ${q(h.binary)},`);
  out.push(`    lines: [${h.lines.join(", ")}],`);
  out.push(`    guaCi: ${q(h.guaCi)},`);
  out.push(`    yaoCi: [`);
  for (const y of h.yaoCi) out.push(`      ${q(y)},`);
  out.push(`    ],`);
  if (h.yong) out.push(`    yong: ${q(h.yong)},`);
  out.push(`  },`);
}
out.push(`];`);
out.push(``);

const target = path.join(kitRoot, "src", "data", "classic.ts");
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, out.join("\n"), "utf8");
console.log(`wrote ${path.relative(process.cwd(), target)} (${hexagrams.length} hexagrams, ${trigrams.length} trigrams)`);
